"""Generates supabase/seed.sql from the demo catalog in the Flutter code.

Run from the repository root:  python3 supabase/gen_seed.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "packages/core/lib/src/data/mock_data.dart"
OUT = ROOT / "supabase/seed.sql"

FIELD = re.compile(
    r"(\w+):\s*(Tr\(\s*'((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)',?\s*\)|'((?:[^'\\]|\\.)*)'|Section\.(\w+)|[\d.]+|true|false)",
    re.S,
)

STORE_COLS = {
    "id": "id", "section": "section", "category": "category", "rating": "rating",
    "reviews": "reviews", "etaMin": "eta_min", "etaMax": "eta_max",
    "deliveryFee": "delivery_fee", "minOrder": "min_order", "emoji": "emoji", "phone": "phone",
}
PRODUCT_COLS = {"id": "id", "storeId": "store_id", "price": "price", "emoji": "emoji"}
TR_COLS = {"name": "name", "tags": "tags", "description": "description"}


def sql(v):
    if isinstance(v, str):
        return "'" + v.replace("\\'", "'").replace("'", "''") + "'"
    return str(v)


def parse(block, cols):
    row = {}
    for m in FIELD.finditer(block):
        key, raw, en, ar, s, sec = m.groups()
        if key in TR_COLS and en is not None:
            row[TR_COLS[key] + "_en"], row[TR_COLS[key] + "_ar"] = en, ar
        elif key in cols:
            row[cols[key]] = s if s is not None else sec if sec is not None else raw
            if s is None and sec is None:
                row[cols[key]] = float(raw) if "." in raw else int(raw)
    return row


def inserts(table, rows):
    cols = list(dict.fromkeys(c for r in rows for c in r))
    values = ",\n".join("  (" + ", ".join(sql(r.get(c)) if c in r else "default" for c in cols) + ")" for r in rows)
    return f"insert into public.{table} ({', '.join(cols)}) values\n{values}\non conflict (id) do nothing;\n"


src = SRC.read_text()
stores_src = src[src.index("const seedStores"):src.index("const seedProducts")]
products_src = src[src.index("const seedProducts"):]
stores = [parse(b, STORE_COLS) for b in re.findall(r"\bStore\((.*?)\n  \),", stores_src, re.S)]
products = [parse(b, PRODUCT_COLS) for b in re.findall(r"\bProduct\((.*?)\n  \),", products_src, re.S)]

OUT.write_text(
    "-- Demo stores and products. Generated by supabase/gen_seed.py, do not edit by hand.\n\n"
    + inserts("stores", stores) + "\n" + inserts("products", products)
)
print(f"Wrote {len(stores)} stores and {len(products)} products to {OUT.relative_to(ROOT)}")
