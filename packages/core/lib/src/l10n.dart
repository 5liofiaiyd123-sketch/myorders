extension L10nX on BuildContext {
  Locale get locale => Localizations.localeOf(this);
  bool get isArabic => locale.languageCode == 'ar';
  String t(String key) => (_strings[key] ?? Tr(key, key)).of(locale);
  String tr(Tr text) => text.of(locale);
  String price(double value) => '${value.toStringAsFixed(0)} ${t('egp')}';
  String status(OrderStatus s) => t('status.${s.name}');
  String section(Section s) => t(s.name);
  String get listSeparator => isArabic ? '، ' : ', ';
}
